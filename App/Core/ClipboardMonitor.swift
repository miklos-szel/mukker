import AppKit
import Foundation

/// Polls NSPasteboard for changes and persists new text/image items.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let repository: ClipboardRepository
    private let pollInterval: TimeInterval = 0.2
    private var timer: Timer?
    private var lastChangeCount: Int = NSPasteboard.general.changeCount

    init(repository: ClipboardRepository = ClipboardRepository()) {
        self.repository = repository
    }

    func start() {
        stop()
        let timer = Timer(timeInterval: pollInterval, repeats: true) { [weak self] _ in
            self?.tick()
        }
        // Lets the system coalesce this wake-up with others; a copy landing in
        // history up to 100 ms later is invisible.
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Log.clipboard.info("Clipboard monitor started")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Lets the fast-append service suppress one capture cycle after it
    /// writes a merged result back to the pasteboard.
    func suppressNextChange() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func tick() {
        // The timer fires on RunLoop.main, so we're on the main thread.
        MainActor.assumeIsolated {
            tickOnMain()
        }
    }

    @MainActor
    private func tickOnMain() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        let sourceApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let settings = ClipboardSettings.shared
        guard shouldRecord(pb, sourceApp: sourceApp, settings: settings) else { return }

        let types = pb.types ?? []

        // File lists first, then images, then strings. A file copy (Finder) also
        // carries the file's icon and its name as a string, so with file lists
        // switched off it must stop here rather than land as an image or text.
        if types.contains(.fileURL) {
            if settings.keepFiles { captureFiles(pb: pb, sourceApp: sourceApp) }
            return
        }
        if (types.contains(.png) || types.contains(.tiff)), settings.keepImages {
            captureImage(pb: pb, sourceApp: sourceApp)
            return
        }
        if types.contains(.string), settings.keepText,
           let str = pb.string(forType: .string),
           !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            captureText(str, pb: pb, sourceApp: sourceApp)
        }
    }

    // MARK: - Capture policy

    /// The single "may this copy be recorded at all" decision, shared by the
    /// poller and fast-append: not from an ignored app and, when
    /// `ignoreConcealedItems` is on, not marked sensitive.
    @MainActor
    func shouldRecord(_ pb: NSPasteboard, sourceApp: String?, settings: ClipboardSettings) -> Bool {
        if let app = sourceApp, settings.ignoredBundleIDs.contains(app) {
            Log.clipboard.debug("Skipping clipboard from ignored app \(app, privacy: .public)")
            return false
        }
        if settings.ignoreConcealedItems, isSensitiveCopy(pb, settings: settings) {
            Log.clipboard.debug("Skipping sensitive clipboard item")
            return false
        }
        return true
    }

    /// Pasteboard types whose mere presence marks a copy as not-for-history: the
    /// nspasteboard.org conventions (concealed / transient / auto-generated) and
    /// the 1Password app's own marker.
    static let sensitiveTypeIdentifiers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    /// Pure half of the sensitivity check: does this set of pasteboard type
    /// identifiers carry one of the opt-out markers?
    static func isSensitive(typeIdentifiers: [String]) -> Bool {
        typeIdentifiers.contains { sensitiveTypeIdentifiers.contains($0) }
    }

    /// Whether the current pasteboard should be treated as sensitive and skipped.
    ///
    /// Two signals, neither of which fires for ordinary copies:
    ///  - the marker types in `sensitiveTypeIdentifiers`: the de-facto convention
    ///    desktop password managers (the 1Password app, etc.) use to opt out of history.
    ///  - A Chromium `org.chromium.source-url` pointing at a known password-manager
    ///    browser-extension popup. Those extensions copy through the browser's normal
    ///    clipboard (no concealed marker) and the frontmost app is the browser, so the
    ///    source URL is the only reliable signal that the copy came from the manager.
    @MainActor
    private func isSensitiveCopy(_ pb: NSPasteboard, settings: ClipboardSettings) -> Bool {
        let types = (pb.types ?? []).map(\.rawValue)
        if Self.isSensitive(typeIdentifiers: types) { return true }

        let sourceURLType = NSPasteboard.PasteboardType("org.chromium.source-url")
        if let data = pb.data(forType: sourceURLType),
           let url = String(data: data, encoding: .utf8),
           let id = Self.chromeExtensionID(from: url),
           settings.passwordManagerExtensionIDs.contains(id) {
            return true
        }
        return false
    }

    /// Extension ID from a `chrome-extension://<id>/…` URL, else nil.
    private static func chromeExtensionID(from url: String) -> String? {
        let prefix = "chrome-extension://"
        guard url.hasPrefix(prefix) else { return nil }
        let id = url.dropFirst(prefix.count).prefix { $0 != "/" }
        return id.isEmpty ? nil : String(id)
    }

    // MARK: - Rich text

    /// Native RTF from the pasteboard, if the source provided it. Cheap — no conversion.
    private func nativeRichText(from pb: NSPasteboard) -> Data? {
        pb.data(forType: .rtf)
    }

    /// RTF for the current pasteboard text: native RTF as-is, else converted from
    /// HTML. The HTML importer is WebKit-backed — slow, and it would fetch any
    /// remote resource the markup names — so the HTML is sanitised first and this
    /// is only called once the text is known to become a new history item.
    @MainActor
    private func richTextData(from pb: NSPasteboard) -> Data? {
        if let rtf = nativeRichText(from: pb) { return rtf }
        guard let html = pb.data(forType: .html) else { return nil }
        let clean = HTMLSanitizer.sanitize(html)
        guard let attr = try? NSAttributedString(
                data: clean,
                options: [.documentType: NSAttributedString.DocumentType.html,
                          .characterEncoding: String.Encoding.utf8.rawValue,
                          .timeout: Self.htmlImportTimeout],
                documentAttributes: nil) else { return nil }
        return try? attr.data(from: NSRange(location: 0, length: attr.length),
                              documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
    }

    /// Seconds the HTML importer may spend on one copy before giving up.
    private static let htmlImportTimeout: TimeInterval = 2

    // MARK: - Capture

    @MainActor
    private func captureText(_ text: String, pb: NSPasteboard, sourceApp: String?) {
        // Ignore text over the configured size limit to avoid history bloat.
        if let limit = ClipboardSettings.shared.maxClipSize.characterLimit,
           text.count > limit {
            Log.clipboard.debug("Skipping clipboard text over max size (\(text.count, privacy: .public) > \(limit, privacy: .public))")
            return
        }
        let hash = ContentHash.sha256Hex(text)

        // A re-copy never pays for an HTML conversion: only native RTF (cheap) is
        // offered to the duplicate path, to fill in a row that has no formatting yet.
        do {
            if let existing = try repository.fetchOne(contentHash: hash) {
                handleDuplicate(existing, label: "text", richText: { self.nativeRichText(from: pb) })
                return
            }
        } catch {
            Log.clipboard.error("Failed to look up text item: \(error.localizedDescription)")
            return
        }

        // Formatting (if any) is stored on disk, named by the same plain-text hash —
        // but only written once the row exists (see `persist`).
        let rtfData = richTextData(from: pb)
        let richURL = rtfData.map { _ in AppPaths.richTextDirectory.appendingPathComponent("\(hash).rtf") }
        let item = ClipItem(
            id: nil,
            kind: .text,
            textContent: text,
            imagePath: nil,
            imageWidth: nil,
            imageHeight: nil,
            previewText: String(text.prefix(200)),
            sourceApp: sourceApp,
            createdAt: Date(),
            pinned: false,
            contentHash: hash,
            lastUsedAt: nil,
            richTextPath: richURL?.path
        )
        var sidecar: Sidecar?
        if let rtfData, let richURL {
            sidecar = Sidecar(data: rtfData, url: richURL, isRequired: false)
        }
        persist(item, label: "text", sidecar: sidecar,
                duplicateRichText: { self.nativeRichText(from: pb) })
    }

    /// Serial, so two quick image copies are canonicalised — and handed back to
    /// the main thread for `persist` — in copy order.
    private let imageQueue = DispatchQueue(label: "ClipboardMonitor.image", qos: .userInitiated)

    /// Reads only the raw pasteboard bytes on the main thread; decoding,
    /// re-encoding and hashing (hundreds of ms for a 5K screenshot) run on
    /// `imageQueue`, then the row is persisted back on main exactly as before.
    @MainActor
    private func captureImage(pb: NSPasteboard, sourceApp: String?) {
        guard let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) else { return }
        // Taken now, not when the background work finishes, so a text copy made
        // meanwhile still sorts as the newer of the two.
        let createdAt = Date()
        // The monitor lives for the whole app run; nothing here races on it —
        // it is only touched again on the main thread.
        nonisolated(unsafe) let monitor = self
        imageQueue.async {
            guard let image = Self.canonicalImage(from: data) else { return }
            // `.common` modes, not `DispatchQueue.main`: a capture made while a
            // menu is tracking must not wait for the menu to close (NSMenu's
            // tracking loop never drains the main dispatch queue). Blocks run
            // in submission order, so copy order is preserved.
            RunLoop.main.perform(inModes: [.common]) {
                MainActor.assumeIsolated {
                    monitor.persistImage(image, sourceApp: sourceApp, createdAt: createdAt)
                }
            }
        }
    }

    @MainActor
    private func persistImage(_ image: CanonicalImage, sourceApp: String?, createdAt: Date) {
        let url = AppPaths.imagesDirectory.appendingPathComponent("\(image.hash).png")
        let item = ClipItem(
            id: nil,
            kind: .image,
            textContent: nil,
            imagePath: url.path,
            imageWidth: image.width,
            imageHeight: image.height,
            previewText: "Image \(image.width)×\(image.height)",
            sourceApp: sourceApp,
            createdAt: createdAt,
            pinned: false,
            contentHash: image.hash,
            lastUsedAt: nil
        )
        persist(item, label: "image", sidecar: Sidecar(data: image.png, url: url, isRequired: true))
    }

    /// A pasteboard image re-encoded to the canonical PNG that is stored and hashed.
    struct CanonicalImage: Equatable {
        let png: Data
        let width: Int
        let height: Int
        /// `ContentHash` of `png` — the dedupe key and the sidecar's file name.
        let hash: String
    }

    /// Re-encodes pasteboard PNG/TIFF bytes to the canonical stored PNG. Pure and
    /// thread-safe (it only touches objects it creates), so it runs off main.
    ///
    /// Deliberately the same NSImage → TIFF → `NSBitmapImageRep` → PNG pipeline
    /// as earlier builds, not ImageIO: the hash of these exact bytes is the dedupe
    /// key already stored for every image in users' histories, and ImageIO's
    /// encoder produces different bytes for common inputs (it drops the 144-dpi
    /// `pHYs` chunk of a retina screenshot; multi-representation images differ
    /// too), so a re-copy of an existing image would stop deduplicating.
    nonisolated static func canonicalImage(from data: Data) -> CanonicalImage? {
        guard let image = NSImage(data: data),
              let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        // Pixel dimensions from the bitmap rep — image.size is in points and
        // under-reports retina screenshots by the backing scale factor.
        return CanonicalImage(png: png, width: rep.pixelsWide, height: rep.pixelsHigh,
                              hash: ContentHash.sha256Hex(png))
    }

    @MainActor
    private func captureFiles(pb: NSPasteboard, sourceApp: String?) {
        guard let urls = pb.readObjects(forClasses: [NSURL.self]) as? [URL],
              !urls.isEmpty else { return }
        let paths = urls.map(\.path)
        let joined = paths.joined(separator: "\n")
        let hash = ContentHash.sha256Hex(joined)
        let firstName = urls.first?.lastPathComponent ?? ""
        let preview = urls.count == 1
            ? firstName
            : "\(urls.count) files: \(firstName), …"
        let item = ClipItem(
            id: nil,
            kind: .file,
            textContent: joined,
            imagePath: nil,
            imageWidth: nil,
            imageHeight: nil,
            previewText: preview,
            sourceApp: sourceApp,
            createdAt: Date(),
            pinned: false,
            contentHash: hash,
            lastUsedAt: nil
        )
        persist(item, label: "file")
    }

    /// An on-disk file a new row owns (image PNG / RTF). `isRequired`: the row is
    /// useless without it (an image), so a failed write removes the row again.
    private struct Sidecar {
        let data: Data
        let url: URL
        let isRequired: Bool
    }

    /// Inserts `item` and only then writes its sidecar. Writing after the insert
    /// means a duplicate or a failed insert never leaves an unreferenced file
    /// behind, and it is what makes the launch-time orphan sweep race-free: any
    /// sidecar on disk already has its row (see `removeOrphanedSidecarFiles`).
    @MainActor
    private func persist(_ item: ClipItem, label: String, sidecar: Sidecar? = nil,
                         duplicateRichText: (() -> Data?)? = nil) {
        do {
            if var inserted = try repository.insertIfNew(item) {
                guard let id = inserted.id else { return }
                if let sidecar, !writeSidecar(sidecar) {
                    if sidecar.isRequired {
                        try repository.delete(id: id)
                        return
                    }
                    try repository.setRichTextPath(id: id, path: nil)
                    inserted.richTextPath = nil
                }
                Log.clipboard.info("Captured \(label, privacy: .public) item id=\(id)")
                ClipboardCache.shared.insertNew(inserted)
                let trimmed = try repository.trim(to: ClipboardSettings.shared.maxHistoryItems)
                // The repository deleted the rows and their files; the cache must
                // not keep offering them (pasting one would write nothing).
                for victim in trimmed {
                    if let victimID = victim.id { ClipboardCache.shared.remove(id: victimID) }
                }
                ForeverHistoryArchive.archive(trimmed)
            } else if let existing = try repository.fetchOne(contentHash: item.contentHash) {
                handleDuplicate(existing, label: label, richText: duplicateRichText)
            }
        } catch {
            Log.clipboard.error("Failed to save \(label, privacy: .public) item: \(error.localizedDescription)")
        }
    }

    /// Re-copy of content already in history: bump it to the top (when
    /// `moveToTopOnUse`) instead of silently dropping the capture, and give a text
    /// row that was stored without formatting the copy's RTF.
    @MainActor
    private func handleDuplicate(_ existing: ClipItem, label: String, richText: (() -> Data?)?) {
        guard let id = existing.id else { return }
        let moveToTop = ClipboardSettings.shared.moveToTopOnUse
        do {
            var changed = false
            if existing.kind == .text, existing.richTextPath == nil, let rtf = richText?() {
                // Same ordering as a new row: reference first, then write.
                let url = AppPaths.richTextDirectory.appendingPathComponent("\(existing.contentHash).rtf")
                try repository.setRichTextPath(id: id, path: url.path)
                if writeSidecar(Sidecar(data: rtf, url: url, isRequired: false)) {
                    changed = true
                } else {
                    try repository.setRichTextPath(id: id, path: nil)
                }
            }
            if moveToTop {
                try repository.bumpLastUsed(id: id)
                changed = true
            }
            guard changed, let refreshed = try repository.fetchOne(id: id) else { return }
            if moveToTop {
                ClipboardCache.shared.upsert(refreshed)
            } else {
                ClipboardCache.shared.update(refreshed)
            }
            Log.clipboard.debug("Refreshed duplicate \(label, privacy: .public) item id=\(id)")
        } catch {
            Log.clipboard.error("Failed to refresh duplicate \(label, privacy: .public) item: \(error.localizedDescription)")
        }
    }

    private func writeSidecar(_ sidecar: Sidecar) -> Bool {
        do {
            try AppPaths.writePrivateFile(sidecar.data, to: sidecar.url)
            return true
        } catch {
            Log.clipboard.error("Failed to write \(sidecar.url.lastPathComponent, privacy: .public): \(error.localizedDescription)")
            return false
        }
    }
}

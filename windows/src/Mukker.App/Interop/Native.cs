    /// <summary>Marks our own synthetic input so the fast-append hook can ignore it.</summary>
    public static readonly IntPtr MukkerInputTag = new(0x4D4B4B52); // "MKKR"

    public static INPUT Key(ushort vk, bool up) => new()
    {
        type = INPUT_KEYBOARD,
        U = new InputUnion { ki = new KEYBDINPUT { wVk = vk, dwFlags = up ? KEYEVENTF_KEYUP : 0, dwExtraInfo = MukkerInputTag } },
    };

    public static void SendKeys(params INPUT[] inputs) => SendInput((uint)inputs.Length, inputs, Marshal.SizeOf<INPUT>());

    /// <summary>Releases modifiers that may still be held from the hotkey, then sends Ctrl+V.</summary>
    public static void SendPaste()
    {
        const ushort VK_CONTROL = 0x11, VK_SHIFT = 0x10, VK_MENU = 0x12, VK_LWIN = 0x5B, VK_RWIN = 0x5C, VK_V = 0x56;
        var list = new System.Collections.Generic.List<INPUT>();
        foreach (var m in new[] { VK_SHIFT, VK_MENU, VK_LWIN, VK_RWIN })
            if ((GetAsyncKeyState(m) & 0x8000) != 0) list.Add(Key(m, true));
        list.Add(Key(VK_CONTROL, false));
        list.Add(Key(VK_V, false));
        list.Add(Key(VK_V, true));
        list.Add(Key(VK_CONTROL, true));
        SendKeys(list.ToArray());
    }

    public static void SendWheel(int notches)
    {
        var input = new INPUT
        {
            type = INPUT_MOUSE,
            U = new InputUnion { mi = new MOUSEINPUT { mouseData = notches * 120, dwFlags = MOUSEEVENTF_WHEEL, dwExtraInfo = MukkerInputTag } },
        };
        SendInput(1, new[] { input }, Marshal.SizeOf<INPUT>());
    }

    /// <summary>Brings <paramref name="hwnd"/> to the foreground, working around the foreground lock.</summary>
    public static void ForceForeground(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero || !IsWindow(hwnd)) return;
        if (IsIconic(hwnd)) ShowWindow(hwnd, 9 /* SW_RESTORE */);
        var fg = GetForegroundWindow();
        if (fg == hwnd) return;
        var fgThread = GetWindowThreadProcessId(fg, out _);
        var cur = GetCurrentThreadId();
        var attached = fgThread != cur && AttachThreadInput(cur, fgThread, true);
        SetForegroundWindow(hwnd);
        if (attached) AttachThreadInput(cur, fgThread, false);
    }

    public static string? ProcessNameOfWindow(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero) return null;
        GetWindowThreadProcessId(hwnd, out var pid);
        if (pid == 0) return null;
        try
        {
            using var p = System.Diagnostics.Process.GetProcessById((int)pid);
            return p.ProcessName;
        }
        catch { return null; }
    }

    public static bool IsOwnWindow(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero) return false;
        GetWindowThreadProcessId(hwnd, out var pid);
        return pid == (uint)Environment.ProcessId;
    }

    /// <summary>Rounded corners on Windows 11 for borderless windows.</summary>
    public static void RoundCorners(IntPtr hwnd)
    {
        var pref = 2; // DWMWCP_ROUND
        try { DwmSetWindowAttribute(hwnd, DWMWA_WINDOW_CORNER_PREFERENCE, ref pref, sizeof(int)); } catch { }
    }
